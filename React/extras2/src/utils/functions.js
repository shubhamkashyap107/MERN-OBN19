export const sum = (a,b) => {
    console.log("ADD")

    return a + b
}

export const mul = (a,b) => {
    console.log("MULTIPLY")
    return a * b
}

export const div = (a,b) => {
    console.log("DIVIDE")

    return a / b
}

export const diff = (a,b) => {
    console.log("DIFF")

    return a - b
}